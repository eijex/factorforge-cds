"""Shared Evaluator for all Generator Candidates."""
from typing import Dict, Any

from factorforge.analysis.metrics import calculate_gc, amino_acid_identity, translate_dna
from factorforge.evaluation.models import (
    EvaluationResult,
    SequenceIntegrity,
    Metrics,
    CheckResult,
    CheckDomain,
    CheckEnforcement,
    CheckResultValue,
)
from factorforge.evaluation.metrics import (
    calculate_polya_motifs,
    calculate_homopolymers,
    calculate_direct_repeats,
)


def _clean_sequence(seq: str) -> str:
    return "".join(seq.upper().split())


class SharedEvaluator:
    """Canonical evaluator for CDS candidates generated by any method (Profile, DP, LM)."""

    def __init__(self, version: str = "1.0.0"):
        self.version = version

    def evaluate_candidate(
        self,
        candidate_dna: str,
        expected_protein: str,
        candidate_id: str = "unknown",
        # TODO: Add constraint_profile and design_spec in later versions
    ) -> EvaluationResult:
        """Evaluate a candidate DNA against an expected protein sequence."""
        dna = _clean_sequence(candidate_dna)
        protein = _clean_sequence(expected_protein).rstrip("*")
        
        # 1. Sequence Integrity
        translated = translate_dna(dna)
        internal_stop_count = translated[:-1].count("*")
        aa_id = amino_acid_identity(protein, dna)
        frame_valid = len(dna) % 3 == 0

        integrity = SequenceIntegrity(
            aa_identity=aa_id,
            frame_valid=frame_valid,
            internal_stop_count=internal_stop_count,
        )

        # 2. Metrics
        gc = calculate_gc(dna)
        # CAI requires codon usage reference which we'll wire up later in Phase A.
        metrics = Metrics(
            cai=None, 
            gc_percent=gc,
            mfe=None,
        )

        # 3. Apply Checks
        checks = []
        
        # Invariant: AA Identity must be 1.0
        checks.append(CheckResult(
            check_name="aa_identity",
            domain=CheckDomain.SEQUENCE_INTEGRITY,
            enforcement=CheckEnforcement.HARD_FAIL,
            result=CheckResultValue.PASS if aa_id == 1.0 else CheckResultValue.FAIL,
            message=f"AA Identity is {aa_id:.3f}",
        ))

        # Invariant: No internal stops
        checks.append(CheckResult(
            check_name="internal_stop",
            domain=CheckDomain.SEQUENCE_INTEGRITY,
            enforcement=CheckEnforcement.HARD_FAIL,
            result=CheckResultValue.PASS if internal_stop_count == 0 else CheckResultValue.FAIL,
            message=f"Found {internal_stop_count} internal stop codons",
        ))

        # Advisory: PolyA Motifs
        poly_a = calculate_polya_motifs(dna)
        checks.append(CheckResult(
            check_name="polya_motif",
            domain=CheckDomain.RNA_RISK,
            enforcement=CheckEnforcement.WARNING,
            result=CheckResultValue.WARNING if poly_a else CheckResultValue.PASS,
            message=f"Found PolyA motifs: {poly_a}" if poly_a else "No PolyA motifs >= 6 found",
        ))

        # Advisory: Homopolymers
        homopolymers = calculate_homopolymers(dna)
        checks.append(CheckResult(
            check_name="homopolymer",
            domain=CheckDomain.RNA_RISK,
            enforcement=CheckEnforcement.WARNING,
            result=CheckResultValue.WARNING if homopolymers else CheckResultValue.PASS,
            message=f"Found homopolymers: {homopolymers}" if homopolymers else "No homopolymers >= 6 found",
        ))

        return EvaluationResult(
            candidate_id=candidate_id,
            evaluator_version=self.version,
            sequence_integrity=integrity,
            metrics=metrics,
            checks=checks,
        )
