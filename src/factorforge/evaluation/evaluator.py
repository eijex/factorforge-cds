"""Shared Evaluator for all Generator Candidates."""
import hashlib
from typing import Dict, Any, List, Set, Optional

from factorforge.analysis.metrics import calculate_gc, amino_acid_identity, translate_dna, calculate_cai
from factorforge.constraints.type_iis import TYPE_IIS_MOTIFS
from factorforge.evaluation.models import (
    EvaluationResult,
    SequenceIntegrity,
    Metrics,
    CheckResult,
    CheckDomain,
    CheckEnforcement,
    CheckResultValue,
)
from factorforge.analysis.sequence_risks import (
    scan_polya,
    scan_homopolymers,
    scan_repeats,
)


def _clean_sequence(seq: str) -> str:
    return "".join(seq.upper().split())


class SharedEvaluator:
    """Canonical evaluator for CDS candidates generated by any method (Profile, DP, LM)."""

    def __init__(self, version: str = "1.0.1", codon_weights: Optional[Dict[str, float]] = None):
        self.version = version
        self.codon_weights = codon_weights

    def evaluate_candidate(
        self,
        candidate_dna: str,
        expected_protein: str,
        candidate_id: str = "unknown",
        target_gc_min_percent: Optional[float] = None,
        target_gc_max_percent: Optional[float] = None,
        forbidden_type_iis: Optional[Set[str]] = None,
        upstream_context: Optional[str] = None,
        stop_codon: Optional[str] = None,
        downstream_context: Optional[str] = None,
        ramp_length_codons: int = 15,
        initiation_mfe_threshold: float = -12.0,
    ) -> EvaluationResult:
        """Evaluate a candidate DNA against an expected protein sequence."""
        dna = _clean_sequence(candidate_dna)
        protein = _clean_sequence(expected_protein).rstrip("*")
        
        # 1. Sequence Integrity
        translated = translate_dna(dna)
        internal_stop_count = translated[:-1].count("*")
        aa_id = amino_acid_identity(protein, dna)
        frame_valid = len(dna) % 3 == 0

        integrity = SequenceIntegrity(
            aa_identity=aa_id,
            frame_valid=frame_valid,
            internal_stop_count=internal_stop_count,
        )

        # 2. Metrics
        gc_percent = calculate_gc(dna)
        cai_val = calculate_cai(dna, self.codon_weights) if self.codon_weights else None
        
        # Segmental CAI & GC
        codons = [dna[j:j+3] for j in range(0, len(dna), 3) if len(dna[j:j+3]) == 3]
        k = min(ramp_length_codons, len(codons))
        ramp_codons = codons[:k]
        body_codons = codons[k:]
        
        cai_5p_ramp = calculate_cai("".join(ramp_codons), self.codon_weights) if (self.codon_weights and ramp_codons) else None
        cai_body = calculate_cai("".join(body_codons), self.codon_weights) if (self.codon_weights and body_codons) else None
        
        ramp_gc = calculate_gc("".join(ramp_codons)) if ramp_codons else None
        body_gc = calculate_gc("".join(body_codons)) if body_codons else None

        from factorforge.engines.profile.scoring import compute_mfe_evidence, compute_5p_mfe_evidence
        mfe_evidence = compute_mfe_evidence(dna)
        mfe_5p_evidence = compute_5p_mfe_evidence(dna, upstream_context=upstream_context)
        
        context_str = f"up={upstream_context or ''}|cds_5p={dna[:45]}|stop={stop_codon or ''}|down={downstream_context or ''}"
        context_digest = hashlib.sha256(context_str.encode("utf-8")).hexdigest()[:16]

        metrics = Metrics(
            cai=cai_val, 
            gc_percent=gc_percent,
            mfe=mfe_evidence.get("mfe_kcal_mol"),
            mfe_status=mfe_evidence.get("mfe_status"),
            mfe_reason=mfe_evidence.get("mfe_reason"),
            mfe_warning=mfe_evidence.get("mfe_warning"),
            mfe_5p_window=mfe_5p_evidence.get("mfe_5p_window_kcal_mol"),
            mfe_5p_status=mfe_5p_evidence.get("mfe_5p_status"),
            cai_5p_ramp=cai_5p_ramp,
            cai_body=cai_body,
            gc_5p_ramp_percent=ramp_gc,
            gc_body_percent=body_gc,
            context_digest=context_digest,
        )

        # 3. Apply Checks
        checks = []
        
        # Invariant: Frame must be valid
        checks.append(CheckResult(
            check_name="frame_valid",
            domain=CheckDomain.SEQUENCE_INTEGRITY,
            enforcement=CheckEnforcement.HARD_FAIL,
            result=CheckResultValue.PASS if frame_valid else CheckResultValue.FAIL,
            message=None if frame_valid else f"Sequence length ({len(dna)}) is not divisible by 3",
        ))

        # Invariant: AA Identity must be 1.0
        checks.append(CheckResult(
            check_name="aa_identity",
            domain=CheckDomain.SEQUENCE_INTEGRITY,
            enforcement=CheckEnforcement.HARD_FAIL,
            result=CheckResultValue.PASS if aa_id == 1.0 else CheckResultValue.FAIL,
            message=None if aa_id == 1.0 else f"AA Identity is {aa_id:.3f}",
        ))

        # Invariant: No internal stops
        checks.append(CheckResult(
            check_name="internal_stop",
            domain=CheckDomain.SEQUENCE_INTEGRITY,
            enforcement=CheckEnforcement.HARD_FAIL,
            result=CheckResultValue.PASS if internal_stop_count == 0 else CheckResultValue.FAIL,
            message=None if internal_stop_count == 0 else f"Found {internal_stop_count} internal stop codons",
        ))

        # Configured Gate: GC Content (only if requested)
        if target_gc_min_percent is not None and target_gc_max_percent is not None:
            # Assuming min/max are provided as percentages (0-100)
            gc_pass = target_gc_min_percent <= gc_percent <= target_gc_max_percent
            checks.append(CheckResult(
                check_name="gc_content",
                domain=CheckDomain.CODON_COMPOSITION,
                enforcement=CheckEnforcement.GATE,
                result=CheckResultValue.PASS if gc_pass else CheckResultValue.FAIL,
                message=None if gc_pass else f"GC {gc_percent:.2f}% is outside target {target_gc_min_percent:.1f}%-{target_gc_max_percent:.1f}%",
            ))

        # Configured Gate: Type IIS (Full Construct Scope)
        if forbidden_type_iis:
            full_construct_seq = (upstream_context or "") + dna + (stop_codon or "") + (downstream_context or "")
            for e_name in forbidden_type_iis:
                motifs = TYPE_IIS_MOTIFS.get(e_name, [])
                found = [m for m in motifs if m in full_construct_seq]
                checks.append(CheckResult(
                    check_name=f"type_iis_{e_name.lower()}",
                    domain=CheckDomain.ASSEMBLY,
                    enforcement=CheckEnforcement.GATE,
                    result=CheckResultValue.FAIL if found else CheckResultValue.PASS,
                    message=f"Found forbidden {e_name} sites in construct: {found}" if found else None,
                ))

        # Advisory: PolyA Signals (Real biological signals)
        poly_a_violations = scan_polya(dna)
        checks.append(CheckResult(
            check_name="polya_signal",
            domain=CheckDomain.RNA_RISK,
            enforcement=CheckEnforcement.WARNING,
            result=CheckResultValue.WARNING if poly_a_violations else CheckResultValue.PASS,
            message=f"Found {len(poly_a_violations)} PolyA signals" if poly_a_violations else "No PolyA signals found",
        ))

        # Advisory: Homopolymers (Any base)
        homopolymers = scan_homopolymers(dna)
        checks.append(CheckResult(
            check_name="homopolymer",
            domain=CheckDomain.RNA_RISK,
            enforcement=CheckEnforcement.WARNING,
            result=CheckResultValue.WARNING if homopolymers else CheckResultValue.PASS,
            message=f"Found {len(homopolymers)} homopolymer runs" if homopolymers else "No homopolymers >= 6 found",
        ))

        # Advisory: Direct Repeats
        repeats = scan_repeats(dna)
        checks.append(CheckResult(
            check_name="direct_repeat",
            domain=CheckDomain.ASSEMBLY,
            enforcement=CheckEnforcement.WARNING,
            result=CheckResultValue.WARNING if repeats else CheckResultValue.PASS,
            message=f"Found {len(repeats)} direct repeats" if repeats else "No major direct repeats found",
        ))

        # Advisory: 5' Initiation Window Hairpin Risk (Thermodynamic MFE)
        mfe_5p_val = metrics.mfe_5p_window
        if mfe_5p_val is not None:
            hairpin_risk = mfe_5p_val < initiation_mfe_threshold
            checks.append(CheckResult(
                check_name="initiation_hairpin_risk",
                domain=CheckDomain.RNA_RISK,
                enforcement=CheckEnforcement.WARNING,
                result=CheckResultValue.WARNING if hairpin_risk else CheckResultValue.PASS,
                message=(
                    f"5' initiation window MFE ({mfe_5p_val:.1f} kcal/mol) is more negative than "
                    f"warning threshold ({initiation_mfe_threshold:.1f} kcal/mol), indicating secondary structure risk."
                ) if hairpin_risk else f"5' initiation window MFE ({mfe_5p_val:.1f} kcal/mol) indicates relaxed structure.",
            ))
        else:
            checks.append(CheckResult(
                check_name="initiation_hairpin_risk",
                domain=CheckDomain.RNA_RISK,
                enforcement=CheckEnforcement.WARNING,
                result=CheckResultValue.INDETERMINATE,
                message="5' initiation window MFE was not evaluated (ViennaRNA unavailable in this environment).",
            ))

        return EvaluationResult(
            candidate_id=candidate_id,
            evaluator_version=self.version,
            sequence_integrity=integrity,
            metrics=metrics,
            checks=checks,
        )

